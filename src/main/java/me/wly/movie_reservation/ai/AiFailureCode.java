package me.wly.movie_reservation.ai;

/** Stable diagnostic identifiers; never include provider text, prompts, or invalid field values. */
public enum AiFailureCode {
    HISTORY_INVALID(Stage.SETUP), ASSISTANT_SETUP_FAILED(Stage.SETUP), GENERATION_FAILED(Stage.GENERATION),
    MODEL_TIMEOUT(Stage.MODEL), MODEL_RATE_LIMITED(Stage.MODEL), MODEL_AUTHENTICATION_FAILED(Stage.MODEL),
    MODEL_NOT_FOUND(Stage.MODEL), MODEL_INVALID_REQUEST(Stage.MODEL), MODEL_UNAVAILABLE(Stage.MODEL),
    MODEL_FAILED(Stage.MODEL), MODEL_OUTPUT_TRUNCATED(Stage.MODEL), TOOL_ROUND_LIMIT(Stage.GENERATION),
    GENERATION_BUDGET_EXCEEDED(Stage.GENERATION),
    TOOL_ARGUMENTS_INVALID(Stage.TOOL), TOOL_EXECUTION_FAILED(Stage.TOOL), UNKNOWN_TOOL(Stage.TOOL),
    OUTPUT_PARSING_FAILED(Stage.PARSING),
    RESPONSE_MISSING(Stage.VALIDATION), RESPONSE_CONTENT_MISSING(Stage.VALIDATION),
    FINISH_REASON_INVALID(Stage.VALIDATION), ANSWER_FIELD_INVALID(Stage.VALIDATION),
    TOOL_RESULT_FAILED(Stage.VALIDATION), MOVIE_RESULT_TYPE_INVALID(Stage.VALIDATION),
    SHOWTIME_RESULT_TYPE_INVALID(Stage.VALIDATION), MOVIE_ID_DUPLICATE(Stage.VALIDATION),
    MOVIE_ID_NOT_IN_TOOL_RESULTS(Stage.VALIDATION), SHOWTIME_ID_DUPLICATE(Stage.VALIDATION),
    SHOWTIME_ID_NOT_IN_TOOL_RESULTS(Stage.VALIDATION), MISSING_FIELDS_DUPLICATE(Stage.VALIDATION),
    CLARIFICATION_FIELDS_REQUIRED(Stage.VALIDATION), UNEXPECTED_MISSING_FIELDS(Stage.VALIDATION),
    MOVIE_RECOMMENDATIONS_REQUIRED(Stage.VALIDATION), SHOWTIME_OPTIONS_REQUIRED(Stage.VALIDATION),
    NO_RESULTS_CONTAINS_CARDS(Stage.VALIDATION), NO_RESULTS_WITHOUT_EMPTY_QUERY(Stage.VALIDATION),
    GENERAL_CONTAINS_CARDS(Stage.VALIDATION), MEMORY_SERIALIZATION_FAILED(Stage.MEMORY),
    CONVERSATION_STORE_FAILED(Stage.STORE);

    public enum Stage { REQUEST, STORE, SETUP, GENERATION, MODEL, TOOL, PARSING, VALIDATION, MEMORY }
    private final Stage stage;
    AiFailureCode(Stage stage) { this.stage = stage; }
    public Stage stage() { return stage; }
}
